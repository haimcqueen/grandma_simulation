import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';

const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await mkdir('.artifacts', { recursive: true });
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5174/');
  await page.waitForFunction(() => window.houseLab?.viewer.mode === 'world-simulation' && window.houseLab.viewer.animatedResident?.robot, undefined, { timeout: 60000 });
  // Isolate input/braking checks; test:recovery covers keyboard-triggered falls.
  await page.locator('#hazard-falls').uncheck();
  await page.locator('#reset').click();
  await page.locator('#pause').click();
  const waist = () => page.evaluate(() => window.houseLab.viewer.resident.root.getObjectByName('waist_pitch_joint').quaternion.toArray());
  const grandma = await waist();
  const position = await page.evaluate(() => window.houseLab.simulation.position);
  await page.locator('#posture').selectOption('upright');
  await page.waitForTimeout(150);
  assert.notDeepEqual(await waist(), grandma);
  assert.deepEqual(await page.evaluate(() => window.houseLab.simulation.position), position);
  await page.locator('#posture').selectOption('grandma');
  await page.waitForFunction(() => document.querySelector('#speed').value === '0.77');
  await page.locator('#pause').click();
  await page.keyboard.down('w');
  await page.waitForFunction(() => window.houseLab.simulation.distance > 0.15);
  assert.equal(await page.evaluate(() => window.houseLab.simulation.manual && !window.houseLab.routine.active), true);
  assert.equal(await page.evaluate(() => window.houseLab.viewer.view), 'follow');
  await page.keyboard.up('w');
  await page.waitForFunction(() => window.houseLab.simulation.currentSpeed === 0);
  const stopped = await page.evaluate(() => window.houseLab.simulation.position);
  await page.waitForTimeout(250);
  assert.deepEqual(await page.evaluate(() => window.houseLab.simulation.position), stopped);
  await page.keyboard.down('ArrowLeft');
  await page.waitForFunction(() => window.houseLab.simulation.heading > 0.3);
  await page.keyboard.up('ArrowLeft');
  assert.deepEqual(await page.evaluate(() => window.houseLab.simulation.position), stopped);
  await page.screenshot({ path: '.artifacts/grandma-keyboard.png' });
  await page.keyboard.down('w');
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  const blurred = await page.evaluate(() => window.houseLab.simulation.position);
  await page.waitForTimeout(250);
  await page.keyboard.up('w');
  assert.deepEqual(await page.evaluate(() => window.houseLab.simulation.position), blurred);
  await page.locator('#posture').focus();
  await page.keyboard.press('w');
  await page.waitForTimeout(250);
  assert.deepEqual(await page.evaluate(() => window.houseLab.simulation.position), blurred);
  await page.locator('[data-destination="kitchen"]').click();
  await page.waitForFunction(() => window.houseLab.simulation.status === 'arrived', undefined, { timeout: 20000 });
  assert.equal(await page.evaluate(() => window.houseLab.simulation.manual), false);
  const reusable = await page.evaluate(async () => {
    const { createKeyboardControls } = await import('/src/keyboard-controls.ts');
    const frame = document.createElement('iframe');
    document.body.append(frame);
    const host = frame.contentWindow;
    let starts = 0, clears = 0;
    const input = createKeyboardControls(host, { canDrive: () => true, onDriveStart: () => starts++, onClear: () => clears++ });
    host.dispatchEvent(new KeyboardEvent('keydown', { code: 'ArrowUp', cancelable: true }));
    host.dispatchEvent(new KeyboardEvent('keydown', { code: 'ArrowLeft', cancelable: true }));
    const moving = input.sample();
    input.dispose();
    const stopped = input.sample();
    const before = starts;
    host.dispatchEvent(new KeyboardEvent('keydown', { code: 'ArrowDown', cancelable: true }));
    frame.remove();
    return { moving, stopped, detached: starts === before, clears };
  });
  assert.deepEqual(reusable.moving, { forward: 1, turn: 1 });
  assert.deepEqual(reusable.stopped, { forward: 0, turn: 0 });
  assert.equal(reusable.detached, true);
  assert.equal(reusable.clears, 1);
  assert.deepEqual(errors, []);
  console.log('Grandma and keyboard checks pass: posture switching, forward movement, turning, braking, blur, form focus, route resumption.');
} finally {
  await browser.close();
}
