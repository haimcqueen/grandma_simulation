import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
try {
 await mkdir('.artifacts', {recursive:true});
 await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5174/simulation.html');
 await page.waitForFunction(()=>window.houseLab?.viewer.mode==='world-simulation',{}, {timeout:60000});
 await page.locator('#reset').click();
 await page.locator('[data-view="map"]').click();
 await page.waitForFunction(()=>!document.querySelector('#map-legend').hidden);
 const top=await page.evaluate(()=>{const v=window.houseLab.viewer;return {orthographic:v.activeCamera.isOrthographicCamera,rotation:v.topControls.enableRotate,resident:v.resident.root.parent===v.topScene,map:v.navigationMap.visible,pan:v.topControls.enabled};});
 assert.deepEqual(top,{orthographic:true,rotation:false,resident:true,map:true,pan:true});
 await page.locator('[data-scenario="blocked"]').click();await page.locator('[data-destination="kitchen"]').click();
 assert.equal(await page.evaluate(()=>window.houseLab.simulation.status),'blocked');
 await page.screenshot({path:'.artifacts/top-blocked.png'});
 await page.locator('[data-scenario="clear"]').click();
 await page.waitForFunction(()=>window.houseLab.simulation.distance>.3);
 await page.locator('#pause').click();
 const snapshot=await page.evaluate(()=>window.houseLab.simulation.snapshot());
 await page.screenshot({path:'.artifacts/top-view.png'});
 const canvas=page.locator('canvas');
 const beforePan=await page.evaluate(()=>window.houseLab.viewer.topCamera.position.toArray());
 const box=await canvas.boundingBox();
 await page.mouse.move(box.x+box.width*.6,box.y+box.height*.6);await page.mouse.down();
 await page.mouse.move(box.x+box.width*.6+40,box.y+box.height*.6+30,{steps:5});await page.mouse.up();
 const afterPan=await page.evaluate(()=>window.houseLab.viewer.topCamera.position.toArray());
 assert.notDeepEqual(afterPan,beforePan);assert.ok(Math.abs(afterPan[1]-beforePan[1])<1e-6);
 await canvas.hover();await page.mouse.wheel(0,-150);await page.waitForTimeout(300);
 assert.ok(await page.evaluate(()=>window.houseLab.viewer.topCamera.zoom>1));
 await page.locator('[data-view="interior"]').click();await page.waitForTimeout(300);
 assert.deepEqual(await page.evaluate(()=>window.houseLab.simulation.snapshot()),snapshot);
 assert.equal(await page.evaluate(()=>window.houseLab.viewer.resident.root.parent===window.houseLab.viewer.overlayScene),true);
 assert.equal(await page.evaluate(()=>window.houseLab.viewer.controls.enabled && !window.houseLab.viewer.topControls.enabled),true);
 await page.screenshot({path:'.artifacts/top-return-interior.png'});
 await page.locator('[data-view="map"]').click();await page.setViewportSize({width:390,height:844});await page.waitForTimeout(300);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'.artifacts/top-mobile.png',fullPage:true});
 await page.locator('#environment').selectOption('fixture');await page.locator('[data-view="map"]').click();
 assert.equal(await page.evaluate(()=>window.houseLab.viewer.fixture.root.parent===window.houseLab.viewer.topScene),true);
 await page.locator('[data-view="overview"]').click();
 assert.equal(await page.evaluate(()=>window.houseLab.viewer.fixture.root.parent===window.houseLab.viewer.scene),true);
 assert.deepEqual(errors,[]);
 await writeFile('.artifacts/top-view-validation.json', JSON.stringify({passed:true,checks:['orthographic map','rotation locked, pan/zoom','blocked/recovered movement','pause state preserved across views','resident render ownership restored','mobile layout','fixture top view'],errors},null,2));
 console.log('Top-down map, movement, view switching and mobile checks passed.');
} finally {await browser.close();}
